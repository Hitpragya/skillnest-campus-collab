const STUDENT_COLS = "id,name,email,password_hash,department,year,bio,availability,hours_per_week,skills_json,interests_json,created_at";
const REQUIREMENT_COLS = "id,owner_id,title,type,description,required_skills_json,team_size,deadline,priority,created_at";
const REQUEST_COLS = "id,from_id,to_id,requirement_id,title,type,message,priority,status,created_at,updated_at";
const cols = (list) => list.split(",");

/** Pick the adapter: PostgreSQL when DATABASE_URL is set, otherwise SQLite at DATABASE_PATH.
 *  Accepts a config object or (for backward compatibility) a SQLite path string. */
export async function openDatabase(configOrPath) {
  const config = typeof configOrPath === "string" ? { databasePath: configOrPath } : configOrPath;
  if (config.databaseUrl) return openPostgres({ connectionString: config.databaseUrl });
  return openSqlite(config.databasePath);
}

// ---------------------------------------------------------------- SQLite
export async function openSqlite(databasePath) {
  const { default: Database } = await import("better-sqlite3");
  if (databasePath !== ":memory:") fs.mkdirSync(path.dirname(databasePath), { recursive: true });
  const db = new Database(databasePath);
  db.pragma("journal_mode = WAL");
  db.pragma("foreign_keys = ON");
  db.exec(SQLITE_SCHEMA); // idempotent

  const named = (list) => cols(list).map((c) => `@${c}`).join(",");
  const reqSelect = `SELECT r.*, f.name AS from_name, f.department AS from_department, t.name AS to_name, t.department AS to_department
    FROM requests r JOIN students f ON f.id = r.from_id JOIN students t ON t.id = r.to_id`;
  const rqSelect = `SELECT r.*, s.name AS owner_name, s.department AS owner_department
    FROM requirements r JOIN students s ON s.id = r.owner_id`;
  const s = {
    insertStudent: db.prepare(`INSERT INTO students (${STUDENT_COLS}) VALUES (${named(STUDENT_COLS)})`),
    studentByEmail: db.prepare("SELECT * FROM students WHERE email = ?"),
    studentById: db.prepare("SELECT * FROM students WHERE id = ?"),
    allStudents: db.prepare("SELECT * FROM students ORDER BY created_at, id"),
    updateStudentProfile: db.prepare(`UPDATE students SET
      name = @name, department = @department, year = @year, bio = @bio,
      availability = @availability, hours_per_week = @hours_per_week,
      skills_json = @skills_json, interests_json = @interests_json
      WHERE id = @id`),
    insertRequirement: db.prepare(`INSERT INTO requirements (${REQUIREMENT_COLS}) VALUES (${named(REQUIREMENT_COLS)})`),
    requirementById: db.prepare("SELECT * FROM requirements WHERE id = ?"),
    allRequirements: db.prepare(`${rqSelect} ORDER BY r.created_at DESC, r.rowid DESC`),
    ownRequirements: db.prepare(`${rqSelect} WHERE r.owner_id = ? ORDER BY r.created_at DESC, r.rowid DESC`),
    insertRequest: db.prepare(`INSERT INTO requests (${REQUEST_COLS}) VALUES (${named(REQUEST_COLS)})`),
    requestById: db.prepare("SELECT * FROM requests WHERE id = ?"),
    requestDetails: db.prepare(`${reqSelect} WHERE r.id = ?`),
    resolve: db.prepare("UPDATE requests SET status = ?, updated_at = ? WHERE id = ? AND to_id = ? AND status = 'pending'"),
  };
  const list = {};
  for (const [dir, col] of [["incoming", "to_id"], ["outgoing", "from_id"]]) {
    list[dir] = {
      pending: db.prepare(`${reqSelect} WHERE r.${col} = ? AND r.status = 'pending' ORDER BY r.sequence ASC`),
      resolved: db.prepare(`${reqSelect} WHERE r.${col} = ? AND r.status = ? ORDER BY r.updated_at DESC, r.sequence DESC`),
    };
  }

  return {
    kind: "sqlite",
    findStudentById: async (id) => s.studentById.get(id),
    findStudentByEmail: async (email) => s.studentByEmail.get(email),
    listStudents: async () => s.allStudents.all(),
    insertStudent: async (row) => void s.insertStudent.run(row),
    updateStudentProfile: async (id, row) => {
      s.updateStudentProfile.run({ ...row, id });
      return s.studentById.get(id);
    },
    findRequirementById: async (id) => s.requirementById.get(id),
    insertRequirement: async (row) => void s.insertRequirement.run(row),
    listRequirements: async (ownerId) => (ownerId ? s.ownRequirements.all(ownerId) : s.allRequirements.all()),
    insertRequest: async (row) => {
      s.insertRequest.run({ status: "pending", ...row });
      return s.requestDetails.get(row.id);
    },
    findRequestById: async (id) => s.requestById.get(id),
    findRequestDetails: async (id) => s.requestDetails.get(id),
    listRequests: async (userId, direction, status) => {
      const st = list[direction === "outgoing" ? "outgoing" : "incoming"];
      return status === "pending" ? st.pending.all(userId) : st.resolved.all(userId, status);
    },
    resolveRequest: async (id, recipientId, status) =>
      db.transaction(() => {
        const changed = s.resolve.run(status, new Date().toISOString(), id, recipientId).changes;
        if (changed === 1) return { result: "ok" };
        return diagnose(s.requestById.get(id), recipientId);
      })(),
    close: async () => db.close(),
  };
}

function diagnose(row, recipientId) {
  if (!row) return { result: "not_found" };
  if (row.to_id !== recipientId) return { result: "forbidden" };
  return { result: "already_resolved", status: row.status };
}

// ---------------------------------------------------------------- PostgreSQL
/** Options: { connectionString } for a real server (Neon), or { pool } to inject a pool (tests). */
export async function openPostgres({ connectionString, pool: injected } = {}) {
  let pool = injected;
  if (!pool) {
    const { default: pg } = await import("pg");
    // Neon URLs include sslmode=require; pg reads SSL settings from the URL itself.
    pool = new pg.Pool({ connectionString, max: 5 });
  }
  for (const sql of PG_SCHEMA) await pool.query(sql); // idempotent

  const one = async (sql, params) => (await pool.query(sql, params)).rows[0];
  const all = async (sql, params) => (await pool.query(sql, params)).rows;
  const placeholders = (list) => cols(list).map((_, i) => `$${i + 1}`).join(",");
  const values = (list, row) => cols(list).map((c) => row[c] ?? null);

  const reqSelect = `SELECT r.id, r.from_id, r.to_id, r.requirement_id, r.title, r.type, r.message, r.priority, r.status,
      r.created_at, r.updated_at, r.sequence_no AS sequence,
      f.name AS from_name, f.department AS from_department, t.name AS to_name, t.department AS to_department
    FROM requests r JOIN students f ON f.id = r.from_id JOIN students t ON t.id = r.to_id`;
  const rqSelect = `SELECT r.id, r.owner_id, r.title, r.type, r.description, r.required_skills_json, r.team_size,
      r.deadline, r.priority, r.created_at, s.name AS owner_name, s.department AS owner_department
    FROM requirements r JOIN students s ON s.id = r.owner_id`;
  const requestSql = (col, pending) =>
    pending
      ? `${reqSelect} WHERE r.${col} = $1 AND r.status = 'pending' ORDER BY r.sequence_no ASC`
      : `${reqSelect} WHERE r.${col} = $1 AND r.status = $2 ORDER BY r.updated_at DESC, r.sequence_no DESC`;

  return {
    kind: "postgres",
    findStudentById: (id) => one(`SELECT ${STUDENT_COLS} FROM students WHERE id = $1`, [id]),
    findStudentByEmail: (email) => one(`SELECT ${STUDENT_COLS} FROM students WHERE lower(email) = lower($1)`, [email]),
    listStudents: () => all(`SELECT ${STUDENT_COLS} FROM students ORDER BY created_at, id`),
    insertStudent: async (row) => {
      await pool.query(`INSERT INTO students (${STUDENT_COLS}) VALUES (${placeholders(STUDENT_COLS)})`, values(STUDENT_COLS, row));
    },
    updateStudentProfile: async (id, row) => one(
      `UPDATE students SET name = $1, department = $2, year = $3, bio = $4,
       availability = $5, hours_per_week = $6, skills_json = $7, interests_json = $8
       WHERE id = $9 RETURNING ${STUDENT_COLS}`,
      [row.name, row.department, row.year, row.bio, row.availability, row.hours_per_week,
        row.skills_json, row.interests_json, id],
    ),
    findRequirementById: (id) => one(`SELECT ${REQUIREMENT_COLS} FROM requirements WHERE id = $1`, [id]),
    insertRequirement: async (row) => {
      await pool.query(`INSERT INTO requirements (${REQUIREMENT_COLS}) VALUES (${placeholders(REQUIREMENT_COLS)})`, values(REQUIREMENT_COLS, row));
    },
    listRequirements: (ownerId) =>
      ownerId
        ? all(`${rqSelect} WHERE r.owner_id = $1 ORDER BY r.created_at DESC, r.sequence_no DESC`, [ownerId])
        : all(`${rqSelect} ORDER BY r.created_at DESC, r.sequence_no DESC`),
    insertRequest: async (row) => {
      await pool.query(`INSERT INTO requests (${REQUEST_COLS}) VALUES (${placeholders(REQUEST_COLS)})`, values(REQUEST_COLS, { status: "pending", ...row }));
      return one(`${reqSelect} WHERE r.id = $1`, [row.id]);
    },
    findRequestById: (id) => one(`SELECT ${REQUEST_COLS} FROM requests WHERE id = $1`, [id]),
    findRequestDetails: (id) => one(`${reqSelect} WHERE r.id = $1`, [id]),
    listRequests: (userId, direction, status) => {
      const col = direction === "outgoing" ? "from_id" : "to_id";
      return status === "pending" ? all(requestSql(col, true), [userId]) : all(requestSql(col, false), [userId, status]);
    },
    // Single conditional UPDATE: atomic in PostgreSQL (row lock), so only one response can succeed.
    resolveRequest: async (id, recipientId, status) => {
      const res = await pool.query(
        "UPDATE requests SET status = $1, updated_at = $2 WHERE id = $3 AND to_id = $4 AND status = 'pending' RETURNING id",
        [status, new Date().toISOString(), id, recipientId],
      );
      if (res.rowCount === 1) return { result: "ok" };
      return diagnose(await one(`SELECT ${REQUEST_COLS} FROM requests WHERE id = $1`, [id]), recipientId);
    },
    close: () => pool.end(),
  };
}
