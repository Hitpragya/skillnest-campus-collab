// Persistence layer. The database is the source of truth for all stored data.
//
// Two adapters implement ONE async repository interface used by app.js:
//   - SQLite (better-sqlite3)  -> local development and the API test suite (DATABASE_PATH)
//   - PostgreSQL (pg Pool)     -> free hosted mode, e.g. Neon (DATABASE_URL)
// Both return rows with the same snake_case column names (plus joined owner/from/to names),
// so the row mappers in app.js do not care which database is in use.
// skills/interests/required skills are stored as JSON text in both databases for identical mapping.
//
// Repository interface (all methods return Promises):
//   findStudentById(id) / findStudentByEmail(email) / listStudents() / insertStudent(row) / updateStudentProfile(id, row)
//   findRequirementById(id) / insertRequirement(row) / listRequirements(ownerIdOrNull)
//   insertRequest(row) -> request details row / findRequestById(id) / findRequestDetails(id)
//   listRequests(userId, "incoming"|"outgoing", "pending"|"accepted"|"rejected")
//     pending  -> ascending arrival sequence (the order sent to the C++ scheduler)
//     resolved -> newest update first
//   resolveRequest(id, recipientId, status) -> { result: "ok"|"not_found"|"forbidden"|"already_resolved", status? }
//     The UPDATE itself checks recipient + pending status, so two concurrent responses cannot both win.
//   close()
import fs from "node:fs";
import path from "node:path";

const SQLITE_SCHEMA = `
CREATE TABLE IF NOT EXISTS students (
  id             TEXT PRIMARY KEY,
  name           TEXT NOT NULL,
  email          TEXT NOT NULL UNIQUE COLLATE NOCASE,
  password_hash  TEXT NOT NULL,
  department     TEXT NOT NULL,
  year           INTEGER NOT NULL CHECK (year BETWEEN 1 AND 6),
  bio            TEXT,
  availability   TEXT NOT NULL DEFAULT 'available' CHECK (availability IN ('available','limited','busy')),
  hours_per_week INTEGER,
  skills_json    TEXT NOT NULL DEFAULT '[]',
  interests_json TEXT NOT NULL DEFAULT '[]',
  created_at     TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS requirements (
  id                   TEXT PRIMARY KEY,
  owner_id             TEXT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  title                TEXT NOT NULL,
  type                 TEXT NOT NULL CHECK (type IN ('project','hackathon','study','placement')),
  description          TEXT NOT NULL,
  required_skills_json TEXT NOT NULL DEFAULT '[]',
  team_size            INTEGER NOT NULL CHECK (team_size BETWEEN 1 AND 20),
  deadline             TEXT,
  priority             INTEGER NOT NULL CHECK (priority BETWEEN 1 AND 3),
  created_at           TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_requirements_owner ON requirements(owner_id);

CREATE TABLE IF NOT EXISTS requests (
  sequence       INTEGER PRIMARY KEY AUTOINCREMENT,
  id             TEXT NOT NULL UNIQUE,
  from_id        TEXT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  to_id          TEXT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  requirement_id TEXT REFERENCES requirements(id) ON DELETE SET NULL,
  title          TEXT NOT NULL,
  type           TEXT NOT NULL CHECK (type IN ('project','hackathon','study','placement')),
  message        TEXT,
  priority       INTEGER NOT NULL CHECK (priority BETWEEN 1 AND 3),
  status         TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','accepted','rejected')),
  created_at     TEXT NOT NULL,
  updated_at     TEXT NOT NULL,
  CHECK (from_id <> to_id)
);
CREATE INDEX IF NOT EXISTS idx_requests_to_status ON requests(to_id, status, sequence);
CREATE INDEX IF NOT EXISTS idx_requests_from ON requests(from_id);
`;

// PostgreSQL schema. Differences from SQLite: identity columns instead of AUTOINCREMENT/rowid,
// and a unique index on lower(email) instead of COLLATE NOCASE.
